// Builds the "Keyboard shortcuts" table of README.md from src/lib/hotkeys.json (IV-06).
// `node scripts/hotkeys-markdown.mjs --write` updates README.md; the interface tests check it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const BEGIN = "<!-- hotkeys:begin (generated by scripts/hotkeys-markdown.mjs) -->";
export const END = "<!-- hotkeys:end -->";

/**
 * @param {{ keys: { keys: string, action: string, done: boolean }[] }} table
 * @param {{ hotkeys: Record<string, string> }} english
 * @returns {string}
 */
export function hotkeysMarkdown(table, english) {
  const rows = table.keys.map(
    (key) => `| ${key.keys} | ${english.hotkeys[key.action].replaceAll("*", "\\*")}${key.done ? "" : " *(coming)*"} |`,
  );
  return [BEGIN, "| Key | Action |", "|---|---|", ...rows, END].join("\n");
}

/** README text with the generated section put between the markers. */
export function withHotkeys(readme, section) {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start < 0 || end < 0) throw new Error("README.md has no hotkeys markers");
  return readme.slice(0, start) + section + readme.slice(end + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("..", import.meta.url);
  const table = JSON.parse(readFileSync(new URL("src/lib/hotkeys.json", root), "utf8"));
  const english = JSON.parse(readFileSync(new URL("locales/en.json", root), "utf8"));
  const readmeUrl = new URL("README.md", root);
  const updated = withHotkeys(readFileSync(readmeUrl, "utf8"), hotkeysMarkdown(table, english));
  if (process.argv.includes("--write")) writeFileSync(readmeUrl, updated);
  else process.stdout.write(updated);
}
